@router.get("/models")
def list_models(db: Session = Depends(get_db), current=Depends(require_permission("child:read", "research:read", "admin:system"))):
    rows = db.scalars(select(ModelVersion).order_by(ModelVersion.created_at.desc())).all()
    return [
        {
            "id": str(r.id),
            "model_key": r.model_key,
            "version": r.version,
            "architecture": r.architecture,
            "status": r.status.value,
            "embedding_dimension": r.embedding_dimension,
            "embedding_space_id": r.embedding_space_id,
            "is_demo": r.is_demo,
            "activated_at": r.activated_at.isoformat() if r.activated_at else None,
            "evaluation_metrics": r.evaluation_metrics,
        }
        for r in rows
    ]


@router.get("/models/{model_id}")
def get_model(model_id: UUID, db: Session = Depends(get_db), current=Depends(require_permission("admin:system", "research:read"))):
    row = db.get(ModelVersion, model_id)
    if not row:
        raise HTTPException(404, "Model not found")
    return {
        "id": str(row.id),
        "model_key": row.model_key,
        "version": row.version,
        "architecture": row.architecture,
        "status": row.status.value,
        "is_demo": row.is_demo,
        "notes": row.notes,
        "evaluation_metrics": row.evaluation_metrics,
    }


@router.post("/models/{model_id}/activate")
def activate_model(model_id: UUID, request=None, db: Session = Depends(get_db), current=Depends(require_permission("model:activate"))):
    from datetime import UTC, datetime

    row = db.get(ModelVersion, model_id)
    if not row:
        raise HTTPException(404, "Model not found")
    for other in db.scalars(select(ModelVersion).where(ModelVersion.status == ModelStatus.ACTIVE)).all():
        other.status = ModelStatus.RETIRED
    row.status = ModelStatus.ACTIVE
    row.activated_at = datetime.now(UTC)
    write_audit(
        db,
        action=AuditAction.MODEL_VERSION_ACTIVATED,
        resource_type="model_version",
        resource_id=str(row.id),
        user_id=current.id,
        role=current.role.value,
        metadata={"model": f"{row.model_key}-{row.version}", "not_clinically_validated": True},
    )
    return {"ok": True, "status": row.status.value}
